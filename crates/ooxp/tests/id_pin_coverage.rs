fn help_ops(format: &str) -> Vec<String> {
    let request = serde_json::json!({"schemaVersion": 1, "action": "help", "format": format});
    match run(&request.to_string()) {
        Ok(RunOutput::Help(value)) => value["ops"]
            .as_array()
            .unwrap()
            .iter()
            .map(|item| item["op"].as_str().unwrap().to_string())
            .collect(),
        other => panic!("help 应返回帮助 JSON，得到 {other:?}"),
    }
}

#[test]
fn help_ops_are_in_the_coverage_table() {
    for format in ["xlsx", "docx", "pptx"] {
        let ops = help_ops(format);
        let listed: Vec<&Row> = ROWS.iter().filter(|row| row.format == format).collect();
        let mut names: Vec<&str> = listed.iter().map(|row| row.op).collect();
        names.sort_unstable();
        let mut unique = names.clone();
        unique.dedup();
        assert_eq!(names, unique, "{format} 覆盖表有重复 op");
        let mut expected = ops.clone();
        expected.sort();
        assert_eq!(names, expected, "{format} 的 help op 与覆盖表不一致");
        for row in listed {
            assert!(!row.family.is_empty(), "{} {} 缺族", row.format, row.op);
            assert!(!row.test.is_empty(), "{} {} 缺测试", row.format, row.op);
        }
    }
}
